%RUN_GLOBAL_STABILITY_CASE_V6 可直接改参数的一键全局稳定性分析脚本。
%
% 使用方法：
% 1. 直接修改下面“参数区”的值。
% 2. 在 MATLAB 中运行本脚本。
% 3. 结果会写到 outputs/mat/<case_name>/ 下。
%
% Part3Variant 说明：
% - 'current_v6'：当前生产链路正在使用的 Part3
% - 'pre_pressure_fix_20260414'：保留的旧版本，仅用于对照

paths = setup_double_wedge_paths();
project_root = paths.project_root;
baseflow_default = fullfile(project_root, 'double_wedge_baseflow.dat');
benchmark_profile = 'sidharth2018_code_correction_v1';

%% 参数区
baseflow_file = baseflow_default;                 % 改成你的基流文件路径
expected_dims = [270, 128];                       % 改成实际基流网格，例如 [812, 382]
stride_x = 1;                                    % x 方向降采样步长
stride_y = 1;                                    % y 方向降采样步长
top_type = 'inlet';                              % 当前双楔案例通常用 'inlet'
case_name = 'manual_global_stability_case_v6';   % 输出目录名
sigma_shift_list = [];                           % 留空表示单个 sigma_shift；填数组表示自动扫描
lock_sigma_triplet_to_shift = true;              % 扫描时是否把 SigmaTriplet 锁成当前单个 shift

run_part4 = true;                                % true: 跑完整全局稳定性分析；false: 只停在 Part3
reuse_existing_case = false;                     % true: 复用已有 case 目录结果
part3_variant = 'current_v6';                    % 'current_v6' 或 'pre_pressure_fix_20260414'

beta = 0.0;                                      % spanwise wavenumber
n_eigs = 80;                                     % 求解特征值个数
sigma_shift = 0.05 + 0.02i;                      % 主 shift
sigma_triplet = [];                              % [] 表示用默认 shift 组
krylov_dimension_floor = [];                     % [] 表示用默认值
krylov_dimension_cap = [];                       % [] 表示用默认值

force_low_memory_descriptor = false;             % true: 强制按大系统低内存策略规划 descriptor solve
use_sponge = false;                              % 是否启用 sponge
use_semi_artificial_viscosity = true;            % 是否启用 Kav
sav_epsilon = 5.0e-2;                            % SAV 系数
sav_shock_percentile = 85.0;                     % SAV shock 传感器百分位
sav_dilation_steps = 5;                          % SAV shock mask 膨胀步数
sav_near_wall_fraction = 0.10;                   % SAV 近壁保护带比例

use_shock_source_regularization = false;         % 是否启用 shock 源项正则化
shock_clip_percentile = 95.0;                    % 二阶导裁剪百分位
shock_dmu_clip_percentile = 95.0;                % dMU/dT 裁剪百分位
zero_second_derivatives_in_shock = true;         % shock 区是否清零二阶导
suppress_viscosity_gradient_terms_in_shock = true; % shock 区是否屏蔽粘性梯度项

use_pressure_row_regularization = false;         % 是否启用压力方程行正则化
pressure_gradient_clip_percentile = 95.0;        % px0/a^2 与 py0/a^2 的裁剪百分位
pressure_divergence_clip_percentile = 95.0;      % div0/a^2 的裁剪百分位
suppress_pressure_gradients_in_shock = false;    % 是否将 shock 区压力梯度系数直接置零
suppress_pressure_divergence_in_shock = false;   % 是否将 shock 区散度系数直接置零

%% 运行
if isempty(sigma_shift_list)
    summary = run_user_test_baseflow_fullres_v6( ...
        'BaseflowFile', baseflow_file, ...
        'ExpectedDims', expected_dims, ...
        'StrideX', stride_x, ...
        'StrideY', stride_y, ...
        'TopType', top_type, ...
        'BenchmarkProfile', benchmark_profile, ...
        'UseSponge', use_sponge, ...
        'NEigs', n_eigs, ...
        'Beta', beta, ...
        'SigmaShift', sigma_shift, ...
        'SigmaTriplet', sigma_triplet, ...
        'KrylovDimensionFloor', krylov_dimension_floor, ...
        'KrylovDimensionCap', krylov_dimension_cap, ...
        'ForceLowMemoryDescriptor', force_low_memory_descriptor, ...
        'CaseName', case_name, ...
        'ReuseExistingCase', reuse_existing_case, ...
        'RunPart4', run_part4, ...
        'Part3Variant', part3_variant, ...
        'UseSemiArtificialViscosity', use_semi_artificial_viscosity, ...
        'SavEpsilon', sav_epsilon, ...
        'SavShockPercentile', sav_shock_percentile, ...
        'SavDilationSteps', sav_dilation_steps, ...
        'SavNearWallFraction', sav_near_wall_fraction, ...
        'UseShockSourceRegularization', use_shock_source_regularization, ...
        'ShockClipPercentile', shock_clip_percentile, ...
        'ShockDmuClipPercentile', shock_dmu_clip_percentile, ...
        'ZeroSecondDerivativesInShock', zero_second_derivatives_in_shock, ...
        'SuppressViscosityGradientTermsInShock', suppress_viscosity_gradient_terms_in_shock, ...
        'UsePressureRowRegularization', use_pressure_row_regularization, ...
        'PressureGradientClipPercentile', pressure_gradient_clip_percentile, ...
        'PressureDivergenceClipPercentile', pressure_divergence_clip_percentile, ...
        'SuppressPressureGradientsInShock', suppress_pressure_gradients_in_shock, ...
        'SuppressPressureDivergenceInShock', suppress_pressure_divergence_in_shock);
    disp(summary);
else
    scan = run_sigma_shift_scan_v6( ...
        'ScanCaseName', case_name, ...
        'SigmaShifts', sigma_shift_list, ...
        'LockSigmaTripletToShift', lock_sigma_triplet_to_shift, ...
        'BaseflowFile', baseflow_file, ...
        'ExpectedDims', expected_dims, ...
        'StrideX', stride_x, ...
        'StrideY', stride_y, ...
        'TopType', top_type, ...
        'BenchmarkProfile', benchmark_profile, ...
        'UseSponge', use_sponge, ...
        'NEigs', n_eigs, ...
        'Beta', beta, ...
        'SigmaTriplet', sigma_triplet, ...
        'KrylovDimensionFloor', krylov_dimension_floor, ...
        'KrylovDimensionCap', krylov_dimension_cap, ...
        'ForceLowMemoryDescriptor', force_low_memory_descriptor, ...
        'RunPart4', run_part4, ...
        'Part3Variant', part3_variant, ...
        'UseSemiArtificialViscosity', use_semi_artificial_viscosity, ...
        'SavEpsilon', sav_epsilon, ...
        'SavShockPercentile', sav_shock_percentile, ...
        'SavDilationSteps', sav_dilation_steps, ...
        'SavNearWallFraction', sav_near_wall_fraction, ...
        'UseShockSourceRegularization', use_shock_source_regularization, ...
        'ShockClipPercentile', shock_clip_percentile, ...
        'ShockDmuClipPercentile', shock_dmu_clip_percentile, ...
        'ZeroSecondDerivativesInShock', zero_second_derivatives_in_shock, ...
        'SuppressViscosityGradientTermsInShock', suppress_viscosity_gradient_terms_in_shock, ...
        'UsePressureRowRegularization', use_pressure_row_regularization, ...
        'PressureGradientClipPercentile', pressure_gradient_clip_percentile, ...
        'PressureDivergenceClipPercentile', pressure_divergence_clip_percentile, ...
        'SuppressPressureGradientsInShock', suppress_pressure_gradients_in_shock, ...
        'SuppressPressureDivergenceInShock', suppress_pressure_divergence_in_shock);
    disp(scan.summary_table);
end
