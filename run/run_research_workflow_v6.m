            workflow.stage_records.case_dir(k));
    end
end

function token = local_fmt_num(value)
%LOCAL_FMT_NUM Convert one scalar into a filesystem-safe token.

    token = sprintf('%.4f', value);
    token = strrep(token, '-', 'm');
    token = strrep(token, '.', 'p');
end
