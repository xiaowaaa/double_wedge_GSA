function variants = local_build_regularization_variants(opts)
%LOCAL_BUILD_REGULARIZATION_VARIANTS Build the cheap comparison variants.

    variants = repmat(struct( ...
        'label', '', ...
        'use_shock_source_regularization', false, ...
        'use_pressure_row_regularization', false), 0, 1);

    variants(end + 1) = struct( ... %#ok<AGROW>
        'label', 'baseline', ...
        'use_shock_source_regularization', logical(opts.UseShockSourceRegularization), ...
        'use_pressure_row_regularization', logical(opts.UsePressureRowRegularization));
    variants(end + 1) = struct( ... %#ok<AGROW>
        'label', 'no_shock_source', ...
        'use_shock_source_regularization', false, ...
        'use_pressure_row_regularization', logical(opts.UsePressureRowRegularization));
    if logical(opts.ComparePressureRowRegularization)
        variants(end + 1) = struct( ... %#ok<AGROW>
            'label', 'no_pressure_row', ...
            'use_shock_source_regularization', logical(opts.UseShockSourceRegularization), ...
            'use_pressure_row_regularization', false);
    end
end

function records = local_build_stage_records(workflow)
%LOCAL_BUILD_STAGE_RECORDS Convert stage outputs into one compact table.

    stage_type = {};
    label = {};
    beta = [];
    stage_completed = {};
    case_dir = {};

    for k = 1:numel(workflow.audit_cases)
        stage_type{end + 1, 1} = 'part3_audit'; %#ok<AGROW>
        label{end + 1, 1} = sprintf('audit_beta_%s', local_fmt_num(workflow.audit_cases(k).beta)); %#ok<AGROW>
        beta(end + 1, 1) = workflow.audit_cases(k).beta; %#ok<AGROW>
        stage_completed{end + 1, 1} = workflow.audit_cases(k).summary.stage_completed; %#ok<AGROW>
        case_dir{end + 1, 1} = workflow.audit_cases(k).summary.case_dir; %#ok<AGROW>
    end

    for k = 1:numel(workflow.regularization_compare)
        stage_type{end + 1, 1} = 'regularization_compare'; %#ok<AGROW>
        label{end + 1, 1} = workflow.regularization_compare(k).label; %#ok<AGROW>
        beta(end + 1, 1) = workflow.regularization_compare(k).beta; %#ok<AGROW>
        stage_completed{end + 1, 1} = workflow.regularization_compare(k).summary.stage_completed; %#ok<AGROW>
        case_dir{end + 1, 1} = workflow.regularization_compare(k).summary.case_dir; %#ok<AGROW>
    end

    if ~isempty(fieldnames(workflow.beta_scan))
        stage_type{end + 1, 1} = 'beta_scan'; %#ok<AGROW>
        label{end + 1, 1} = 'beta_scan_coarse'; %#ok<AGROW>
        beta(end + 1, 1) = NaN; %#ok<AGROW>
        if workflow.beta_scan.run_part4
            stage_completed{end + 1, 1} = 'Part4_scan'; %#ok<AGROW>
        else
            stage_completed{end + 1, 1} = 'Part3_scan'; %#ok<AGROW>
        end
        case_dir{end + 1, 1} = workflow.beta_scan.scan_root_dir; %#ok<AGROW>
    end

    if ~isempty(fieldnames(workflow.refined_case))
        stage_type{end + 1, 1} = 'refined_part4'; %#ok<AGROW>
        label{end + 1, 1} = 'refined_part4'; %#ok<AGROW>
        beta(end + 1, 1) = workflow.refined_beta; %#ok<AGROW>
        stage_completed{end + 1, 1} = workflow.refined_case.stage_completed; %#ok<AGROW>
        case_dir{end + 1, 1} = workflow.refined_case.case_dir; %#ok<AGROW>
    end

    if ~isempty(fieldnames(workflow.resolvent_scan))
        stage_type{end + 1, 1} = 'resolvent_scan'; %#ok<AGROW>
        label{end + 1, 1} = 'resolvent_scan'; %#ok<AGROW>
        beta(end + 1, 1) = workflow.resolvent_beta; %#ok<AGROW>
        stage_completed{end + 1, 1} = workflow.resolvent_scan.part3_summary.stage_completed; %#ok<AGROW>
        case_dir{end + 1, 1} = workflow.resolvent_scan.case_dir; %#ok<AGROW>
    end

    records = table(string(stage_type), string(label), beta, string(stage_completed), string(case_dir), ...
        'VariableNames', {'stage_type', 'label', 'beta', 'stage_completed', 'case_dir'});
end

function beta_value = local_resolve_regularization_beta(requested_beta, audit_betas, beta_scan_betas)
%LOCAL_RESOLVE_REGULARIZATION_BETA Pick the compare beta when it is not explicit.

    if ~isempty(requested_beta)
        beta_value = requested_beta;
        return;
    end

    audit_betas = audit_betas(:).';
    beta_scan_betas = beta_scan_betas(:).';
    nonzero_audit = audit_betas(abs(audit_betas) > 1.0e-12);
    if ~isempty(nonzero_audit)
        beta_value = nonzero_audit(1);
    elseif ~isempty(beta_scan_betas)
        beta_value = beta_scan_betas(max(1, min(2, numel(beta_scan_betas))));
    else
        beta_value = 0.0;
    end
end

function beta_value = local_resolve_target_beta(requested_beta, beta_scan_betas, audit_betas, fallback_beta)
%LOCAL_RESOLVE_TARGET_BETA Pick one target beta for refined or resolvent stages.

    if ~isempty(requested_beta)
        beta_value = requested_beta;
        return;
    end

    beta_scan_betas = beta_scan_betas(:).';
    audit_betas = audit_betas(:).';
    nonzero_scan = beta_scan_betas(abs(beta_scan_betas) > 1.0e-12);
    if ~isempty(nonzero_scan)
        beta_value = nonzero_scan(min(4, numel(nonzero_scan)));
    elseif ~isempty(audit_betas)
        beta_value = audit_betas(end);
    else
        beta_value = fallback_beta;
    end
end

