function profile = get_double_wedge_benchmark_profile(profile_name)
%GET_DOUBLE_WEDGE_BENCHMARK_PROFILE Return one named benchmark/profile contract.

    if nargin < 1 || isempty(profile_name)
        profile_name = 'sidharth2018_code_correction_v1';
    end
    profile_name = lower(strtrim(char(string(profile_name))));

    switch profile_name
        case {'sidharth2018', 'sidharth_2018', 'sidharth2018_code_correction', ...
                'sidharth2018_code_correction_v1'}
            profile = local_sidharth2018_code_correction();
        otherwise
            error('get_double_wedge_benchmark_profile:UnknownProfile', ...
                'Unknown double-wedge benchmark profile "%s".', profile_name);
    end
end

